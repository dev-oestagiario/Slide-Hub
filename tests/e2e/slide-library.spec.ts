import {test,expect} from '@playwright/test'
test('F12: move, duplicate and insert a vector shape through the library',async({page})=>{
 await page.goto('/tests/e2e/slide-library.html')
 await page.getByRole('button',{name:'Selecionar slide 2: Seção B'}).click()
 await page.getByRole('button',{name:'Mover seção para trás'}).click()
 const text=page.getByRole('textbox',{name:'Texto da aula'})
 await expect(text).toHaveValue(/## Seção B[\s\S]*# Seção A/)
 await page.getByRole('button',{name:'Duplicar seção'}).click()
 await expect(page.getByRole('navigation',{name:'Miniaturas dos slides'}).getByRole('button')).toHaveCount(3)
 await page.getByRole('button',{name:'Elementos',exact:true}).click()
 await page.getByRole('button',{name:'Inserir Seta',exact:true}).click()
 await expect(page.getByLabel('Prévia da seção').getByRole('img',{name:'Forma arrow'})).toBeVisible()
 await page.getByRole('button',{name:'Ver exportação'}).click()
 await expect(page.locator('.f6-pages').getByRole('img',{name:'Forma arrow'})).toHaveCount(1)
 await expect(page.locator('.f6-pages')).not.toContainText('GABARITO RESERVADO')
})
test('F12: unified history restores text and the previous geometry',async({page})=>{
 await page.goto('/tests/e2e/slide-library.html')
 const text=page.getByRole('textbox',{name:'Texto da aula'})
 const original=await text.inputValue()
 await page.getByRole('button',{name:'Fixar título'}).click()
 const preview=page.getByLabel('Prévia da seção')
 await expect(preview.locator('.f4-pinned')).toHaveAttribute('style',/left: 20%/)
 await text.fill(original.replace('Texto A.','Texto novo A.'))
 await expect(text).toHaveValue(/Texto novo A/)
 await page.getByRole('button',{name:'Desfazer',exact:true}).click()
 await expect(text).toHaveValue(original)
 await expect(preview.locator('.f4-pinned')).toHaveAttribute('style',/left: 20%/)
 await page.getByRole('button',{name:'Desfazer',exact:true}).click()
 await expect(preview.locator('.f4-pinned')).toHaveCount(0)
 await page.getByRole('button',{name:'Refazer',exact:true}).click()
 await expect(preview.locator('.f4-pinned')).toHaveAttribute('style',/left: 20%/)
})


